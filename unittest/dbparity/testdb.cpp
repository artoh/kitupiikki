QString TestDb::normalisoiKaavioSql(const QString& sql)
{
    QString t = sql;
    t.replace(QRegularExpression(QStringLiteral("\\s+")), QStringLiteral(" "));
    t.replace(QStringLiteral("INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL"),
              QStringLiteral("INTEGER IDENTITY PRIMARY KEY"), Qt::CaseInsensitive);
    t.replace(QStringLiteral("INTEGER PRIMARY KEY AUTOINCREMENT"),
              QStringLiteral("INTEGER IDENTITY PRIMARY KEY"), Qt::CaseInsensitive);
    t.replace(QStringLiteral("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
              QStringLiteral("INTEGER IDENTITY PRIMARY KEY"), Qt::CaseInsensitive);
    t.replace(QStringLiteral("GENERATED BY DEFAULT AS IDENTITY"),
              QStringLiteral("IDENTITY"), Qt::CaseInsensitive);
    return t.trimmed();
}

QStringList TestDb::luoSqlTaulut(const QString& sql)
{
    QStringList nimet;
    QRegularExpression re(QStringLiteral("CREATE TABLE\\s+(\\w+)"),
                          QRegularExpression::CaseInsensitiveOption);
    auto it = re.globalMatch(sql);
    while (it.hasNext())
        nimet.append(it.next().captured(1));
    nimet.sort(Qt::CaseInsensitive);
    return nimet;
}

QVariantMap TestDb::luoSqlSarakkeet(const QString& sql)
{
    QVariantMap tulos;
    QRegularExpression tauluRe(QStringLiteral("CREATE TABLE\\s+(\\w+)"),
                               QRegularExpression::CaseInsensitiveOption);
    auto it = tauluRe.globalMatch(sql);
    while (it.hasNext()) {
        auto m = it.next();
        const QString nimi = m.captured(1);
        QString runko = taulunRunko(sql, m.capturedStart());
        runko.replace(QRegularExpression(QStringLiteral("\\s+")), QStringLiteral(" "));
        QStringList sarakkeet;
        for (const QString& rivi : jaaYlimmallaTasolla(runko)) {
            const QString trim = rivi.trimmed();
            if (trim.isEmpty())
                continue;
            const QString yla = trim.toUpper();
            if (yla.startsWith(QLatin1String("PRIMARY KEY"))
                || yla.startsWith(QLatin1String("UNIQUE"))
                || yla.startsWith(QLatin1String("CHECK"))
                || yla.startsWith(QLatin1String("CONSTRAINT"))
                || yla.startsWith(QLatin1String("FOREIGN KEY"))) {
                continue;
            }
            const QString sarake = trim.section(QLatin1Char(' '), 0, 0);
            if (!sarake.isEmpty())
                sarakkeet.append(sarake.toLower());
        }
        tulos.insert(nimi.toLower(), sarakkeet);
    }
    return tulos;
}

QVariant TestDb::normalisoi(const QVariant& arvo)
{
    if (arvo.isNull())
        return QVariant();

    switch (arvo.userType()) {
    case QMetaType::QDate:
        return arvo.toDate().toString(Qt::ISODate);
    case QMetaType::QDateTime:
        return arvo.toDateTime().toUTC().toString(QStringLiteral("yyyy-MM-ddTHH:mm:ss"));
    case QMetaType::QByteArray: {
        const QByteArray ba = arvo.toByteArray();
        const QJsonDocument doc = QJsonDocument::fromJson(ba);
        if (!doc.isNull())
            return QString::fromUtf8(doc.toJson(QJsonDocument::Compact));
        // SQLite often yields TEXT as QByteArray (e.g. Liite.sha).
        if (ba == QString::fromUtf8(ba).toUtf8())
            return QString::fromUtf8(ba);
        return QString::fromLatin1(ba.toHex());
    }
    case QMetaType::Double:
    case QMetaType::Float:
    case QMetaType::Int:
    case QMetaType::UInt:
    case QMetaType::LongLong:
    case QMetaType::ULongLong:
        return normalisoiNumero(arvo.toDouble());
    case QMetaType::QVariantMap: {
        QVariantMap out;
        const QVariantMap in = arvo.toMap();
        for (auto i = in.constBegin(); i != in.constEnd(); ++i)
            out.insert(i.key().toLower(), normalisoi(i.value()));
        return out;
    }
    case QMetaType::QVariantList: {
        QVariantList out;
        for (const QVariant& item : arvo.toList())
            out.append(normalisoi(item));
        return out;
    }
    default:
        break;
    }

    const QString s = arvo.toString();
    static const QRegularExpression numeroRe(QStringLiteral("^-?\\d+(\\.\\d+)?$"));
    if (s.size() <= 18 && numeroRe.match(s).hasMatch())
        return normalisoiNumero(s.toDouble());
    if (s.startsWith(QLatin1Char('{')) || s.startsWith(QLatin1Char('['))) {
        const QJsonDocument doc = QJsonDocument::fromJson(s.toUtf8());
        if (!doc.isNull())
            return QString::fromUtf8(doc.toJson(QJsonDocument::Compact));
    }
    return s;
}

QVariantList TestDb::dump(QSqlDatabase db, const QString& sql)
{
    QSqlQuery query(db);
    QVariantList rivit;
    if (!query.exec(sql))
        return rivit;
    while (query.next()) {
        QVariantMap rivi;
        const QSqlRecord rec = query.record();
        for (int i = 0; i < rec.count(); ++i) {
            QVariant arvo = rec.value(i);
            if (arvo.isNull() || arvo.toString().isEmpty())
                continue;
            rivi.insert(rec.fieldName(i).toLower(), normalisoi(arvo));
        }
        rivit.append(rivi);
    }
    return rivit;
}

QStringList TestDb::taulut(QSqlDatabase db)
{
    QStringList nimet;
    QSqlQuery query(db);
    if (db.driverName() == QLatin1String("QSQLITE")) {
        query.exec(QStringLiteral(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite%' ORDER BY name COLLATE NOCASE"));
    } else {
        query.exec(QStringLiteral(
            "SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY tablename"));
    }
    while (query.next())
        nimet.append(query.value(0).toString());
    return nimet;
}

QStringList TestDb::sarakkeet(QSqlDatabase db, const QString& taulu)
{
    QStringList nimet;
    QSqlQuery query(db);
    if (db.driverName() == QLatin1String("QSQLITE")) {
        query.exec(QStringLiteral("PRAGMA table_info(%1)").arg(taulu));
        while (query.next())
            nimet.append(query.value(1).toString().toLower());
    } else {
        query.prepare(QStringLiteral(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema='public' AND lower(table_name)=lower(?) "
            "ORDER BY ordinal_position"));
        query.addBindValue(taulu.toLower());
        query.exec();
        while (query.next())
            nimet.append(query.value(0).toString().toLower());
    }
    return nimet;
}

