bool TestDb::alusta()
{
    sqlitePolku_ = portable_.filePath(QStringLiteral("parity.kitsas"));
    postgresDbNimi_ = postgresYhteys().database;

    if (!QSqlDatabase::isDriverAvailable(QStringLiteral("QPSQL"))) {
        postgresVirhe_ = QStringLiteral("QPSQL driver is not available");
        return true;
    }

    postgresKaytossa_ = pudotaJaLuoPostgresTietokanta();
    return true;
}

bool TestDb::pudotaJaLuoPostgresTietokanta()
{
    const PostgresYhteys yhteys = postgresYhteys();
    const QString hallintaNimi = QStringLiteral("KITSAS_PARITY_PG_DROP");
    if (QSqlDatabase::contains(hallintaNimi)) {
        QSqlDatabase::database(hallintaNimi).close();
        QSqlDatabase::removeDatabase(hallintaNimi);
    }

    {
        QSqlDatabase hallinta = QSqlDatabase::addDatabase(QStringLiteral("QPSQL"), hallintaNimi);
        hallinta.setHostName(yhteys.host);
        hallinta.setPort(yhteys.port);
        hallinta.setDatabaseName(envTai("KITSAS_PG_ADMIN_DB", QStringLiteral("postgres")));
        hallinta.setUserName(yhteys.username);
        hallinta.setPassword(yhteys.password);
        if (!hallinta.open()) {
            postgresVirhe_ = hallinta.lastError().text();
            hallinta.close();
            QSqlDatabase::removeDatabase(hallintaNimi);
            return false;
        }
        QSqlQuery q(hallinta);
        q.exec(QStringLiteral(
                   "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                   "WHERE datname='%1' AND pid <> pg_backend_pid()")
                   .arg(postgresDbNimi_));
        q.exec(QStringLiteral("DROP DATABASE IF EXISTS %1 WITH (FORCE)").arg(postgresDbNimi_));
        hallinta.close();
    }
    QSqlDatabase::removeDatabase(hallintaNimi);

    return kp()->postgres()->luoTietokanta(yhteys.hallintaYhteys(), postgresDbNimi_, false);
}

