static QString envTai(const char* avain, const QString& oletus)
{
    const QString arvo = QProcessEnvironment::systemEnvironment().value(QString::fromLatin1(avain));
    return arvo.isEmpty() ? oletus : arvo;
}

static QString normalisoiNumero(double arvo)
{
    if (qAbs(arvo - qRound64(arvo)) < 1e-9)
        return QString::number(qRound64(arvo));
    return QString::number(arvo, 'f', 4);
}

static QString taulunRunko(const QString& sql, int createPos)
{
    const int alku = sql.indexOf(QLatin1Char('('), createPos);
    if (alku < 0)
        return QString();
    int syvyys = 0;
    for (int i = alku; i < sql.size(); ++i) {
        if (sql.at(i) == QLatin1Char('('))
            ++syvyys;
        else if (sql.at(i) == QLatin1Char(')')) {
            --syvyys;
            if (syvyys == 0)
                return sql.mid(alku + 1, i - alku - 1);
        }
    }
    return QString();
}

static QStringList jaaYlimmallaTasolla(const QString& teksti)
{
    QStringList osat;
    QString nykyinen;
    int syvyys = 0;
    for (QChar c : teksti) {
        if (c == QLatin1Char('('))
            ++syvyys;
        else if (c == QLatin1Char(')'))
            --syvyys;
        if (c == QLatin1Char(',') && syvyys == 0) {
            osat.append(nykyinen.trimmed());
            nykyinen.clear();
        } else {
            nykyinen += c;
        }
    }
    if (!nykyinen.trimmed().isEmpty())
        osat.append(nykyinen.trimmed());
    return osat;
}

