void TestDb::sulje()
{
    if (!kp() || !kp()->yhteysModel())
        return;
    kp()->yhteysAvattu(nullptr);
}

bool TestDb::avaaSqlite()
{
    sulje();
    QFile::remove(sqlitePolku_);
    if (!kp()->sqlite()->uusiKirjanpito(sqlitePolku_, initials())) {
        qWarning() << "SQLite uusiKirjanpito failed for" << sqlitePolku_;
        return false;
    }
    return kp()->sqlite()->avaaTiedosto(sqlitePolku_, false);
}

bool TestDb::avaaPostgres()
{
    sulje();
    if (!postgresKaytossa_)
        return false;
    if (!pudotaJaLuoPostgresTietokanta())
        return false;
    return kp()->postgres()->uusiKirjanpito(postgresYhteys(), initials(), false);
}

QVariant TestDb::kysy(const QString& polku, KpKysely::Metodi metodi, const QVariant& data)
{
    KpKysely *kysely = kpk(polku, metodi);
    if (!kysely)
        return QVariant();
    QVariant tulos;
    QObject::connect(kysely, &KpKysely::vastaus, [&](QVariant *reply) {
        if (reply)
            tulos = *reply;
    });
    kysely->kysy(data);
    return tulos;
}

QVariant TestDb::lahetaTiedosto(const QString& polku, const QByteArray& data, const QMap<QString, QString>& meta)
{
    KpKysely *kysely = kpk(polku, KpKysely::POST);
    if (!kysely)
        return QVariant();
    QVariant tulos;
    QObject::connect(kysely, &KpKysely::vastaus, [&](QVariant *reply) {
        if (reply)
            tulos = *reply;
    });
    kysely->lahetaTiedosto(data, meta);
    return tulos;
}
